#!/usr/bin/env python3
"""Generates the struct layout cross-check between the Rust port and the C oracle.

Parses the #[repr(C)] structs in the files below and writes
  oracle/csrc/layout.c   -- sizeof/offsetof table compiled with libopus
  src/layout_tests.rs    -- the same table computed with size_of/offset_of!, compared in a test
Re-run after changing any of these structs.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [
    "src/silk/structs.rs",
    "src/silk/float/structs_flp.rs",
    "src/celt/entcode.rs",
]
# Rust struct -> (C expression for its expected size, Rust path)
SIZE_OVERRIDE = {
    # mono-only: C allocates silk_encoder without the second channel state
    "silk_encoder": "sizeof(silk_encoder) - sizeof(silk_encoder_state_FLP)",
}

entries = []  # (name, c_expr, rust_expr)
for src in SOURCES:
    text = (ROOT / src).read_text()
    mod = "crate::" + src[len("src/"):-len(".rs")].replace("/", "::")
    for m in re.finditer(r"#\[repr\(C\)\]\s*(?:#\[[^\]]*\]\s*)*pub (struct|union) (\w+) \{(.*?)\n\}", text, re.S):
        kind, name, body = m.groups()
        if kind == "union":
            continue
        rust_ty = f"{mod}::{name}"
        entries.append((name, SIZE_OVERRIDE.get(name, f"sizeof({name})"), f"size_of::<{rust_ty}>()"))
        for f in re.finditer(r"^\s*pub (\w+):", body, re.M):
            field = f.group(1)
            entries.append((f"{name}.{field}", f"offsetof({name}, {field})", f"offset_of!({rust_ty}, {field})"))

c = ["/* Generated by scripts/gen_layout.py; do not edit. */",
     "#include <stddef.h>",
     '#include "structs_FLP.h"',
     '#include "control.h"',
     '#include "entcode.h"',
     "",
     "const struct { const char *name; int value; } minisilk_layout[] = {"]
c += [f'    {{ "{n}", (int)({e}) }},' for n, e, _ in entries]
c += ["};", f"const int minisilk_layout_count = {len(entries)};", ""]
(ROOT / "oracle/csrc/layout.c").write_text("\n".join(c))

r = ["//! Generated by scripts/gen_layout.py; do not edit.",
     "//! Checks that the `#[repr(C)]` structs have the same layout as the C oracle build.",
     "",
     "use core::ffi::{c_char, c_int, CStr};",
     "use core::mem::{offset_of, size_of};",
     "",
     "#[repr(C)]",
     "struct Entry {",
     "    name: *const c_char,",
     "    value: c_int,",
     "}",
     "",
     'unsafe extern "C" {',
     "    static minisilk_layout: [Entry; 0];",
     "    static minisilk_layout_count: c_int;",
     "}",
     "",
     "#[test]",
     "fn struct_layout_matches_c() {",
     "    let rust: &[(&str, usize)] = &["]
r += [f'        ("{n}", {e}),' for n, _, e in entries]
r += ["    ];",
      "    let c = unsafe { core::slice::from_raw_parts(minisilk_layout.as_ptr(), minisilk_layout_count as usize) };",
      "    assert_eq!(c.len(), rust.len(), \"regenerate with scripts/gen_layout.py\");",
      "    let mut bad = 0;",
      "    for (e, (name, value)) in c.iter().zip(rust) {",
      "        let cname = unsafe { CStr::from_ptr(e.name) }.to_str().unwrap();",
      "        assert_eq!(cname, *name, \"regenerate with scripts/gen_layout.py\");",
      "        if e.value as usize != *value {",
      "            println!(\"layout mismatch: {name}: C {} vs Rust {value}\", e.value);",
      "            bad += 1;",
      "        }",
      "    }",
      "    assert_eq!(bad, 0, \"{bad} layout mismatches\");",
      "}",
      ""]
(ROOT / "src/layout_tests.rs").write_text("\n".join(r))
print(f"{len(entries)} entries")
