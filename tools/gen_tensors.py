# Writes src/tensors.ts: where each weight of the pinned model.onnx sits, in the slot order sat.wat reads.
import json
from paths import ROOT
lay = json.load(open(f"{ROOT}/layout.json")); T = lay["tensors"]
MM = [[429, 430, 433, 439, 440, 441], [442, 443, 446, 452, 453, 454], [455, 456, 459, 465, 466, 467]]
names = ["roberta.embeddings.word_embeddings.weight_Q8", "roberta.embeddings.word_embeddings.weight_scales",
         "roberta.embeddings.position_embeddings.weight", "roberta.embeddings.token_type_embeddings.weight",
         "roberta.embeddings.LayerNorm.weight", "roberta.embeddings.LayerNorm.bias"]
for l in range(3):
    for i in MM[l]: names += [f"onnx::MatMul_{i}_Q8", f"onnx::MatMul_{i}_scales"]
    p = f"roberta.encoder.layer.{l}."
    names += [p + s for s in ["attention.self.query.bias", "attention.self.key.bias", "attention.self.value.bias",
              "attention.output.dense.bias", "attention.output.LayerNorm.weight", "attention.output.LayerNorm.bias",
              "intermediate.dense.bias", "output.dense.bias", "output.LayerNorm.weight", "output.LayerNorm.bias"]]
names += ["onnx::MatMul_468_Q8", "onnx::MatMul_468_scales", "classifier.bias"]
assert len(names) == 75 and set(names) == set(T)
rows = "\n".join(f"  [{T[n]['offset']}, {T[n]['bytes']}], // {n} {T[n]['dims']}" for n in names)
open(f"{ROOT}/src/tensors.ts", "w").write(f"""// Generated by tools/gen_tensors.py from the pinned model.onnx (sha256 1132546a…be99f): [file offset,
// bytes] of each weight's raw data, in the slot order of sat.wat. A different file means regenerating this.
export const MODEL_SIZE = {lay['size']};
export const TENSORS: readonly (readonly [number, number])[] = [
{rows}
];
""")
print("ok")
