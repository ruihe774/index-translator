#!/usr/bin/env python3
"""One-shot converter of SILK table sources to Rust statics (kept for reference/regeneration).

usage: gen_tables.py <opus-src> <out-dir>
Arrays become `pub static NAME: [T; N] = [...]` (shape inferred from the initializer).
Pointer arrays and codebook structs are emitted from the hand-written SPECIAL entries.
"""
import re
import sys
from pathlib import Path

TYPES = {"opus_uint8": "u8", "opus_int8": "i8", "opus_int16": "i16", "opus_int32": "i32"}
FILES = [
    "tables_gain.c", "tables_LTP.c", "tables_NLSF_CB_WB.c", "tables_other.c",
    "tables_pitch_lag.c", "tables_pulses_per_block.c", "table_LSF_cos.c", "pitch_est_tables.c",
]
# Tables of features this port drops (stereo, LBRR, bandwidth transitions).
SKIP = {
    "silk_stereo_pred_quant_Q13", "silk_stereo_pred_joint_iCDF", "silk_stereo_only_code_mid_iCDF",
    "silk_LBRR_flags_2_iCDF", "silk_LBRR_flags_3_iCDF", "silk_LBRR_flags_iCDF_ptr",
    "silk_Transition_LP_B_Q28", "silk_Transition_LP_A_Q28",
}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def parse_init(s, i=0):
    """Parses a brace initializer starting at s[i] == '{'. Returns (nested list, next index)."""
    assert s[i] == "{"
    i += 1
    out, tok = [], ""
    while True:
        c = s[i]
        if c == "{":
            v, i = parse_init(s, i)
            out.append(v)
            continue
        if c in ",}":
            if tok.strip():
                out.append(tok.strip())
            tok = ""
            i += 1
            if c == "}":
                return out, i
            continue
        tok += c
        i += 1


def shape(v):
    if isinstance(v, list):
        inner = [shape(x) for x in v]
        assert all(x == inner[0] for x in inner), "ragged initializer"
        return [len(v)] + (inner[0] if inner else [])
    return []


def rust_type(t, shp):
    for n in reversed(shp):
        t = f"[{t}; {n}]"
    return t


def fmt(v, indent=1):
    if not isinstance(v[0], list):
        items = [x for x in v]
        lines, line = [], ""
        for x in items:
            piece = x + ", "
            if len(line) + len(piece) > 96:
                lines.append(line.rstrip())
                line = ""
            line += piece
        lines.append(line.rstrip())
        pad = "    " * indent
        return "[\n" + "\n".join(pad + l for l in lines) + "\n" + "    " * (indent - 1) + "]"
    pad = "    " * indent
    return "[\n" + "".join(pad + fmt(x, indent + 1) + ",\n" for x in v) + "    " * (indent - 1) + "]"


def convert(path):
    text = strip_comments(path.read_text())
    out = []
    for m in re.finditer(r"const\s+(opus_u?int(?:8|16|32))\s+(\w+)\s*((?:\[[^\]]*\]\s*)+)=\s*", text):
        ty, name, _dims = m.groups()
        if name in SKIP:
            continue
        v, _ = parse_init(text, m.end())
        out.append(f"pub static {name}: {rust_type(TYPES[ty], shape(v))} = {fmt(v)};\n")
    return out


def main():
    src, dst = Path(sys.argv[1]) / "silk", Path(sys.argv[2])
    for f in FILES:
        body = convert(src / f)
        mod = dst / (f[:-2] + ".rs")
        header = [f"//! Port of silk/{f} (generated by scripts/gen_tables.py, then hand-edited).", "",
                  "#![allow(non_upper_case_globals)]", ""]
        mod.write_text("\n".join(header) + "\n".join(body))
        print(f"{mod}: {len(body)} tables")


main()
